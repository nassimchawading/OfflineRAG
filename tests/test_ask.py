"""Part 6 check: run the RAG pipeline on a set of questions and compare with "no RAG".

Saves everything to notes/part6_results.md (useful for the report).
Run (Ollama must be running):  .venv\\Scripts\\python.exe tests\\test_ask.py
"""
from pathlib import Path
import sys
import time

import ollama

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
from ask import CHAT_MODEL, answer  # noqa: E402
from search import cite  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
QUESTIONS = [
    "Pourquoi la caractéristique de traction a-t-elle une zone à couple constant et une zone à puissance constante ?",
    "Quel est le couple de serrage d'une vis M16 en acier 8.8 pour une fixation normale ?",
    "What is the tightening torque of an M16 8.8 screw for a normal fixing?",
    "Quelles précautions faut-il prendre avant d'accéder aux équipements haute tension de la motrice ?",
    "Que signifie TCU et quel est son rôle ?",
    "Quelle est la capitale de l'Australie ?",            # not in the manual
    "Quelle est la vitesse maximale du TGV Atlantique ?",  # railway topic, but not in this manual
]
BEFORE_AFTER = QUESTIONS[1]  # asked once WITHOUT the documents, to show what RAG adds

out = ["# Part 6: RAG test results\n", f"Chat model: {CHAT_MODEL}, generated by tests/test_ask.py\n"]

print(f"=== WITHOUT RAG: {BEFORE_AFTER}")
start = time.time()
plain = ollama.chat(model=CHAT_MODEL, messages=[{"role": "user", "content": BEFORE_AFTER}]).message.content
print(plain, f"\n({time.time() - start:.1f} s)\n")
out += ["## Before/after: same question without RAG (model's general knowledge only)\n",
        f"**Q:** {BEFORE_AFTER}\n", f"**Answer without documents:**\n\n{plain}\n"]

for q in QUESTIONS:
    print(f"=== {q}")
    r = answer(q, stream=False)
    t = r["timings"]
    timing = f"search {t['search']:.1f} s"
    if r["lang"] == "en":
        timing = f"translate {t['translate']:.1f} s, " + timing
    if "answer_total" in t:
        timing += (f", answer {t['answer_total']:.1f} s (model load {t['model_load']:.1f} s), "
                   f"{r['tokens_per_s']:.1f} tok/s, prompt {r['prompt_tokens']} tokens")
    sources = "\n".join(f"- [{i}] {cite(h)} (distance {h['distance']:.3f})" for i, h in enumerate(r["sources"], 1))
    print(r["answer"], f"\n{sources or '- (no relevant passage)'}\n({timing})\n")
    out += [f"## {q}\n"]
    if r["lang"] == "en":
        out += [f"*Searched in French as:* {r['search_query']}\n"]
    out += [f"{r['answer']}\n", f"**Sources:**\n{sources or '- (no relevant passage, model not called)'}\n",
            f"*{timing}*\n"]

(ROOT / "notes" / "part6_results.md").write_text("\n".join(out), encoding="utf-8")
print("saved notes/part6_results.md")
